// Render domain-scoped DNS artifacts. Never installs or starts a host service.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { isIP } from 'node:net';
import path from 'node:path';
import { parseProfile } from './profile.mjs';
import { renderHost, renderProjectUrls, resolveAddressing } from './addressing.mjs';
import { resolveProfilePath } from '../bin/setup.mjs';

function fail(message) { throw new Error(`dns: ${message}`); }

export function parseDnsArgs(args) {
  if (args.length === 0 || ['help', '--help', '-h'].includes(args[0])) return { help: true };
  if (args[0] !== 'render') fail('expected render.');
  const options = { targets: [], port: 1053, output: null, apply: false, json: false };
  const seen = new Set();
  for (let i = 1; i < args.length; i++) {
    const arg = args[i];
    if (arg === '--apply' || arg === '--json') {
      if (seen.has(arg)) fail(`${arg} may be supplied only once.`);
      seen.add(arg); options[arg.slice(2)] = true; continue;
    }
    if (!['--project', '--address', '--port', '--output'].includes(arg)) fail(`unknown option ${JSON.stringify(arg)}.`);
    const value = args[++i];
    if (!value || value.startsWith('--')) fail(`${arg} needs a value.`);
    if (arg === '--project') { options.targets.push({ project: value, address: null }); continue; }
    if (arg === '--address') {
      const target = options.targets.at(-1);
      if (!target || target.address != null) fail('--address must follow its --project exactly once.');
      if (isIP(value) !== 4) fail('--address must be an IPv4 ingress address.');
      target.address = value; continue;
    }
    if (seen.has(arg)) fail(`${arg} may be supplied only once.`);
    seen.add(arg);
    if (arg === '--output') options.output = path.resolve(value);
    if (arg === '--port') {
      if (!/^\d+$/.test(value) || Number(value) < 1 || Number(value) > 65535) fail('--port must be an integer from 1 to 65535.');
      options.port = Number(value);
    }
  }
  if (!options.targets.length || options.targets.some((target) => !target.address)) fail('each --project requires an explicit --address.');
  if (options.apply && !options.output) fail('--apply requires --output to name a new artifact directory.');
  return options;
}

export function renderDnsPlan(options) {
  const domains = new Map();
  const projects = options.targets.map(({ project, address }) => {
    const file = resolveProfilePath(project);
    const text = readFileSync(file, 'utf8');
    const profile = parseProfile(text, file);
    const addressing = resolveAddressing(profile, { profilePath: file });
    if (addressing.tld === 'local' || addressing.tld.endsWith('.local') || addressing.tld === 'localhost' || addressing.tld.endsWith('.localhost')) fail(`reserved suffix ${addressing.tld}; use ground.test or a chosen owned domain.`);
    // A zone belongs to one project, unless it explicitly owns an exclusive suffix.
    // Refuse layouts that would accidentally wildcard unrelated projects.
    if (!addressing.scheme.shared.startsWith('{service}.')) fail('DNS wildcard rendering requires shared scheme to start with {service}.');
    const tokens = { service: 'ground-probe', project: profile.project.host, namespace: profile.project.namespace, tld: addressing.tld };
    const domain = renderHost(addressing.scheme.shared, tokens).slice('ground-probe.'.length);
    if (domains.has(domain) && domains.get(domain) !== address) fail(`conflicting ingress addresses for ${domain}.`);
    domains.set(domain, address);
    const names = renderProjectUrls(profile, addressing).shared.map((entry) => entry.host);
    if (profile.overlay.mode === 'on') {
      const overlays = renderProjectUrls(profile, addressing, { env: 'ground-probe' }).overlay;
      if (overlays.some((entry) => !entry.host.endsWith(`.${domain}`))) fail('overlay names must use the same project DNS zone as shared names.');
    }
    return { profile: file, profile_sha256: createHash('sha256').update(text).digest('hex'), project: profile.project.slug, tld: addressing.tld, tld_source: addressing.tldSource, domain, address, names };
  });
  const zones = [...domains].sort(([a], [b]) => a.localeCompare(b)).map(([domain, address]) => ({ domain, address }));
  const lines = ['# Generated by de-novo skills infra dns render; source details: manifest.json', `port=${options.port}`, 'listen-address=127.0.0.1', 'bind-interfaces', 'no-resolv', 'no-hosts'];
  for (const { domain, address } of zones) lines.push(`local=/${domain}/`, `address=/${domain}/${address}`);
  const resolvers = zones.map(({ domain }) => ({ domain, path: `resolvers/${domain}`, content: `# Ground DNS artifact; source details: manifest.json\nnameserver 127.0.0.1\nport ${options.port}\n` }));
  return { schemaVersion: 1, host_modified: false, port: options.port, projects, zones, dnsmasq: lines.join('\n') + '\n', resolvers };
}

function writeArtifacts(output, plan) {
  if (existsSync(output)) fail(`artifact directory already exists: ${output}; existing files are preserved.`);
  const parent = path.dirname(output);
  // Requiring an existing parent avoids leaving unrelated directories on failure.
  if (!existsSync(parent)) fail(`artifact parent does not exist: ${parent}.`);
  const staging = `${output}.staging-${process.pid}-${Date.now()}`;
  mkdirSync(staging, { mode: 0o700 });
  try {
    mkdirSync(path.join(staging, 'resolvers'));
    writeFileSync(path.join(staging, 'dnsmasq.conf'), plan.dnsmasq);
    for (const resolver of plan.resolvers) writeFileSync(path.join(staging, resolver.path), resolver.content);
    writeFileSync(path.join(staging, 'manifest.json'), JSON.stringify(plan, null, 2) + '\n');
    // Atomically reserve the destination: never merge with or replace existing artifacts.
    mkdirSync(output, { mode: 0o700 });
    try {
      for (const name of ['dnsmasq.conf', 'resolvers', 'manifest.json']) renameSync(path.join(staging, name), path.join(output, name));
    } catch (error) { rmSync(output, { recursive: true, force: true }); throw error; }
  } finally { rmSync(staging, { recursive: true, force: true }); }
}

export function runDns(args) {
  const options = parseDnsArgs(args);
  if (options.help) { console.log(dnsHelp()); return 0; }
  const plan = renderDnsPlan(options);
  if (options.apply) writeArtifacts(options.output, plan);
  if (options.json) console.log(JSON.stringify(plan, null, 2));
  else {
    console.log(`DNS zones ${plan.zones.length}/${plan.zones.length}; projects ${plan.projects.length}/${plan.projects.length}; artifacts ${options.apply ? plan.resolvers.length + 2 : 0}/${plan.resolvers.length + 2}; host changes 0`);
    for (const { domain, address } of plan.zones) console.log(`  ${domain} -> ${address}`);
    if (options.apply) console.log(`  output ${options.output}`);
    else console.log(plan.dnsmasq);
  }
  return 0;
}

export function dnsHelp() {
  return `usage: de-novo skills infra dns render --project ROOT --address IPv4 [--project ROOT --address IPv4 ...]
       [--port N] [--output NEW_DIRECTORY --apply] [--json]
Render dnsmasq and macOS per-domain resolver artifacts from effective project addressing.
The catalog default is ground.test. Project and clone domain overrides retain their precedence.
--apply writes a new artifact directory only; it never installs, starts, or changes host DNS.`;
}
